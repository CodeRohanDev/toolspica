// Regenerates src/lib/tools-data.generated.ts from toolslist.md + TOOLS-CHECKLIST.md.
// Run: node scripts/generate-tools-data.mjs
// Single source of truth: edit toolslist.md (add/remove tools) and TOOLS-CHECKLIST.md
// (mark [x] when a tool ships), then re-run this script.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

function slugify(input) {
  return input
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/\(.*?\)/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function parseToolsList(md) {
  const lines = md.split("\n");
  const categories = [];
  let current = null;
  let inNavSection = false;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (line.startsWith("# Categories for Navigation")) {
      inNavSection = true;
      continue;
    }
    if (inNavSection) continue;

    if (line.startsWith("# ")) {
      const name = line.slice(2).trim();
      current = { name, slug: slugify(name), tools: [] };
      categories.push(current);
      continue;
    }

    if (line.startsWith("- ") && current) {
      const name = line.slice(2).trim();
      current.tools.push({ name, slug: slugify(name) });
    }
  }

  return categories;
}

function parseChecklist(md) {
  // Map: tool name -> { tier, done }
  const map = new Map();
  const lines = md.split("\n");
  let tier = null;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    const tierMatch = line.match(/^## Tier (\d)/);
    if (tierMatch) {
      tier = Number(tierMatch[1]);
      continue;
    }
    const itemMatch = line.match(/^- \[( |x)\]\s+(.+)$/);
    if (itemMatch && tier) {
      const done = itemMatch[1] === "x";
      const name = itemMatch[2].trim();
      map.set(name, { tier, done });
    }
  }

  return map;
}

const toolsListMd = readFileSync(path.join(root, "toolslist.md"), "utf8");
const checklistMd = readFileSync(path.join(root, "TOOLS-CHECKLIST.md"), "utf8");

const categories = parseToolsList(toolsListMd);
const checklist = parseChecklist(checklistMd);

let totalTools = 0;
let totalDone = 0;

for (const category of categories) {
  for (const tool of category.tools) {
    const meta = checklist.get(tool.name);
    tool.tier = meta?.tier ?? 1;
    tool.done = meta?.done ?? false;
    totalTools += 1;
    if (tool.done) totalDone += 1;
  }
  // Live tools first, coming-soon last — stable sort preserves original
  // relative order within each group.
  category.tools.sort((a, b) => Number(b.done) - Number(a.done));
}

const header = `// AUTO-GENERATED by scripts/generate-tools-data.mjs — do not hand-edit.
// Source of truth: toolslist.md (structure) + TOOLS-CHECKLIST.md (tier/done status).
// Re-run: node scripts/generate-tools-data.mjs

export interface Tool {
  name: string;
  slug: string;
  tier: number;
  done: boolean;
}

export interface ToolCategory {
  name: string;
  slug: string;
  tools: Tool[];
}

export const TOOL_CATEGORIES: ToolCategory[] = ${JSON.stringify(categories, null, 2)};

const seenSlugs = new Set<string>();
export const ALL_TOOLS: (Tool & { categoryName: string; categorySlug: string })[] =
  TOOL_CATEGORIES.flatMap((category) =>
    category.tools.map((tool) => ({
      ...tool,
      categoryName: category.name,
      categorySlug: category.slug,
    }))
  ).filter((tool) => {
    if (seenSlugs.has(tool.slug)) return false;
    seenSlugs.add(tool.slug);
    return true;
  });

export const TOTAL_TOOLS = ${totalTools};
export const TOTAL_TOOLS_DONE = ${totalDone};
`;

writeFileSync(path.join(root, "src/lib/tools-data.generated.ts"), header);

console.log(
  `Generated tools-data.generated.ts — ${categories.length} categories, ${totalTools} tools (${totalDone} done).`
);
